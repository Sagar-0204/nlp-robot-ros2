#!/usr/bin/env python3
"""Generate the Gazebo world and the matching Nav2 map from nlp_robot/world_spec.py.

Usage (from the package root):
    python3 tools/generate_world.py
Re-run after editing world_spec.py, then `colcon build` again.
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
sys.path.insert(0, PKG)

from nlp_robot import world_spec as W  # noqa: E402


def wall_link(i, x0, y0, x1, y1):
    cx, cy = (x0 + x1) / 2.0, (y0 + y1) / 2.0
    length = math.hypot(x1 - x0, y1 - y0) + W.WALL_THICKNESS
    yaw = math.atan2(y1 - y0, x1 - x0)
    size = f'{length:.3f} {W.WALL_THICKNESS:.3f} {W.WALL_HEIGHT:.3f}'
    return f"""
      <link name="wall_{i}">
        <pose>{cx:.3f} {cy:.3f} {W.WALL_HEIGHT / 2:.3f} 0 0 {yaw:.4f}</pose>
        <collision name="c"><geometry><box><size>{size}</size></box></geometry></collision>
        <visual name="v">
          <geometry><box><size>{size}</size></box></geometry>
          <material>
            <ambient>0.75 0.75 0.75 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse>
            <specular>0.1 0.1 0.1 1</specular>
          </material>
        </visual>
      </link>"""


def box_model(name, x, y, rgb):
    s = W.BOX_SIZE
    r, g, b = rgb
    mass = 0.5
    i = mass * (s * s + s * s) / 12.0
    return f"""
    <model name="{name}">
      <pose>{x:.3f} {y:.3f} {s / 2:.3f} 0 0 0</pose>
      <link name="link">
        <inertial><mass>{mass}</mass>
          <inertia><ixx>{i:.5f}</ixx><iyy>{i:.5f}</iyy><izz>{i:.5f}</izz>
            <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        </inertial>
        <collision name="c">
          <geometry><box><size>{s} {s} {s}</size></box></geometry>
          <surface><friction><ode><mu>0.6</mu><mu2>0.6</mu2></ode></friction></surface>
        </collision>
        <visual name="v">
          <geometry><box><size>{s} {s} {s}</size></box></geometry>
          <material>
            <ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>
            <specular>0.05 0.05 0.05 1</specular><emissive>{r * 0.25:.3f} {g * 0.25:.3f} {b * 0.25:.3f} 1</emissive>
          </material>
        </visual>
      </link>
      <!-- Ground truth for RViz / evaluation only: publishes /model/{name}/pose (the robot
           never uses it to navigate; it must find boxes with its own camera + LiDAR). -->
      <plugin filename="gz-sim-pose-publisher-system" name="gz::sim::systems::PosePublisher">
        <topic>/model/{name}/pose</topic>
        <publish_model_pose>true</publish_model_pose>
        <publish_link_pose>false</publish_link_pose>
        <publish_visual_pose>false</publish_visual_pose>
        <publish_collision_pose>false</publish_collision_pose>
        <publish_sensor_pose>false</publish_sensor_pose>
        <use_pose_vector_msg>false</use_pose_vector_msg>
        <update_frequency>5</update_frequency>
      </plugin>
    </model>"""


def make_sdf():
    walls = ''.join(wall_link(i, *seg) for i, seg in enumerate(W.all_wall_segments()))
    boxes = ''.join(box_model(n, x, y, rgb) for n, (x, y, rgb) in W.BOXES.items())
    return f"""<?xml version="1.0"?>
<!-- GENERATED by tools/generate_world.py from nlp_robot/world_spec.py. Do not edit by hand. -->
<sdf version="1.8">
  <world name="nlp_room">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.8 0.85 0.9 1</background>
      <shadows>false</shadows>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry></collision>
        <visual name="v">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <material><ambient>0.45 0.45 0.45 1</ambient><diffuse>0.5 0.5 0.5 1</diffuse></material>
        </visual>
      </link>
    </model>

    <model name="room_walls">
      <static>true</static>{walls}
    </model>
{boxes}
  </world>
</sdf>
"""


def make_map():
    res = W.MAP_RESOLUTION
    r = W.ROOM
    ox, oy = r['xmin'] - W.MAP_MARGIN, r['ymin'] - W.MAP_MARGIN
    width = int(round((r['xmax'] - r['xmin'] + 2 * W.MAP_MARGIN) / res))
    height = int(round((r['ymax'] - r['ymin'] + 2 * W.MAP_MARGIN) / res))
    pixels = bytearray()
    # PGM rows go top (max y) to bottom (min y)
    for row in range(height):
        y = oy + (height - row - 0.5) * res
        for col in range(width):
            x = ox + (col + 0.5) * res
            occupied = W.distance_to_walls(x, y) <= max(0.0, res / 2.0 - 1e-9)
            if occupied:
                pixels.append(0)
            elif W.inside_room(x, y) and W.distance_to_walls(x, y) > 0:
                pixels.append(254)
            else:
                pixels.append(205)
    header = f'P5\n# generated by nlp_robot/tools/generate_world.py\n{width} {height}\n255\n'.encode()
    return header + bytes(pixels), (ox, oy), (width, height)


def main():
    sdf_path = os.path.join(PKG, 'worlds', 'nlp_room.sdf')
    with open(sdf_path, 'w') as f:
        f.write(make_sdf())
    pgm, (ox, oy), (w, h) = make_map()
    with open(os.path.join(PKG, 'maps', 'nlp_room.pgm'), 'wb') as f:
        f.write(pgm)
    with open(os.path.join(PKG, 'maps', 'nlp_room.yaml'), 'w') as f:
        f.write('# generated by tools/generate_world.py\n'
                'image: nlp_room.pgm\nmode: trinary\n'
                f'resolution: {W.MAP_RESOLUTION}\n'
                f'origin: [{ox:.3f}, {oy:.3f}, 0.0]\n'
                'negate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n')
    bridge_path = os.path.join(PKG, 'config', 'ground_truth_bridge.yaml')
    with open(bridge_path, 'w') as f:
        f.write('# GENERATED by tools/generate_world.py: true box poses from Gazebo -> ROS\n')
        for name in W.BOXES:
            f.write(f'- ros_topic_name: "nlp_robot/ground_truth/{name}"\n'
                    f'  gz_topic_name: "/model/{name}/pose"\n'
                    '  ros_type_name: "geometry_msgs/msg/PoseStamped"\n'
                    '  gz_type_name: "gz.msgs.Pose"\n'
                    '  direction: GZ_TO_ROS\n')
    print(f'wrote {sdf_path}\nwrote map {w}x{h} px, origin ({ox}, {oy})')


if __name__ == '__main__':
    main()
